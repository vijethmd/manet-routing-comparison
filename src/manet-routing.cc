/*
 * Performance Comparison of AODV, OLSR and DSDV Routing Protocols in a
 * Mobile Ad Hoc Network (MANET) Using NS-3
 *
 * Written for ns-3.48. Extends the AODV study (manet-aodv.cc) with a choice of
 * routing protocol, routing overhead and jitter.
 *
 * SCENARIO
 * --------
 *   - N mobile wireless nodes (default 10) in a square area.
 *   - IEEE 802.11b Wi-Fi (11 Mbps) in ad-hoc mode (no access point),
 *     with a 250 m transmission range.
 *   - Every node runs IPv4 with one routing protocol (--protocol):
 *       AODV  Ad hoc On-Demand Distance Vector   reactive        UDP port 654
 *       OLSR  Optimized Link State Routing       proactive       UDP port 698
 *       DSDV  Destination-Sequenced Distance-Vector  proactive   UDP port 269
 *   - Nodes move with the Random Waypoint mobility model: each node picks a
 *     random destination in the area, walks there at the configured speed,
 *     pauses, and repeats.
 *   - ONE source node (node 0) sends Constant Bit Rate (CBR) UDP traffic to
 *     ONE destination node (node N-1). CBR = fixed-size packets sent at a
 *     fixed interval (1 / packetRate seconds).
 *   - FlowMonitor observes the data flow and we compute the performance
 *     metrics listed below.
 *
 * PERFORMANCE METRICS (for the CBR data flow only; routing control packets are excluded)
 * --------------------------------------------------------------------------------
 *   Tx packets  : number of data packets generated by the source application. They
 *                 are counted with the client's "Tx" trace, because OLSR and DSDV drop a
 *                 packet at the source when they have no route, before FlowMonitor sees it.
 *   Source drops: packets dropped at the source for lack of a route (Tx packets minus
 *                 the packets FlowMonitor saw leaving the source; about 0 for AODV,
 *                 which buffers packets during route discovery).
 *   Rx packets  : number of data packets that reached the destination.
 *   Packet loss : Tx packets - Rx packets (packets that never arrived).
 *                 Loss ratio (%) = 100 * lost / Tx.
 *   PDR         : Packet Delivery Ratio = 100 * Rx / Tx   (in %).
 *   Throughput  : bits successfully delivered per second, measured at the IP
 *                 layer (packet + UDP/IP headers) over the traffic period:
 *                     throughput (kbps) = rxBytes * 8 / trafficDuration / 1000
 *   Avg delay   : average end-to-end delay of RECEIVED packets:
 *                     avg delay (ms) = sum(delay of each rx packet) / Rx * 1000
 *                 (delay = time received at destination - time sent by source)
 *   Avg jitter  : mean variation between the delays of consecutive received packets:
 *                     avg jitter (ms) = jitterSum / (Rx - 1) * 1000
 *
 * ROUTING OVERHEAD (all nodes, whole simulation)
 * ----------------------------------------------
 *   Ctrl packets: routing control packets transmitted by every node at the IP layer
 *                 (originated and forwarded, broadcast and unicast), counted on the
 *                 protocol's UDP port. FlowMonitor ignores broadcast packets, so they
 *                 are counted with the Ipv4L3Protocol "Tx" trace instead.
 *   NRL         : Normalised Routing Load = Ctrl packets / Rx packets
 *                 (control packets sent per data packet delivered).
 *
 * USAGE (from ~/Documents/NP AAT/manet-aodv-project, see HOW_TO_RUN.md)
 * -----
 *   ./scripts/run_single.sh --protocol=OLSR --nodes=10 --simTime=60 --speed=5
 *   ./scripts/run_single.sh --PrintHelp     (lists every option)
 */

#include "ns3/aodv-module.h"
#include "ns3/applications-module.h"
#include "ns3/core-module.h"
#include "ns3/dsdv-module.h"
#include "ns3/flow-monitor-module.h"
#include "ns3/internet-module.h"
#include "ns3/mobility-module.h"
#include "ns3/network-module.h"
#include "ns3/olsr-module.h"
#include "ns3/wifi-module.h"

#include <fstream>
#include <iomanip>
#include <iostream>
#include <sstream>

using namespace ns3;

NS_LOG_COMPONENT_DEFINE("ManetRouting");

// Data packets generated by the CBR client, counted by CountAppTx().
static uint64_t g_appTxPackets = 0;

static void
CountAppTx(Ptr<const Packet> /* packet */)
{
    g_appTxPackets++;
}

// Routing overhead counters, filled by CountRoutingTx().
static uint16_t g_routingPort = 0;
static uint64_t g_ctrlPackets = 0;
static uint64_t g_ctrlBytes = 0;

// Called for every IPv4 packet a node transmits (the packet includes the IPv4 header).
// Counts the packets that belong to the routing protocol, identified by its UDP port.
static void
CountRoutingTx(Ptr<const Packet> packet, Ptr<Ipv4> /* ipv4 */, uint32_t /* interface */)
{
    Ptr<Packet> copy = packet->Copy();
    Ipv4Header ipHeader;
    copy->RemoveHeader(ipHeader);
    if (ipHeader.GetProtocol() != 17 || ipHeader.GetFragmentOffset() != 0) // UDP only
    {
        return;
    }
    UdpHeader udpHeader;
    copy->PeekHeader(udpHeader);
    if (udpHeader.GetDestinationPort() == g_routingPort ||
        udpHeader.GetSourcePort() == g_routingPort)
    {
        g_ctrlPackets++;
        g_ctrlBytes += packet->GetSize();
    }
}

int
main(int argc, char* argv[])
{
    // ------------------------------------------------------------------
    // 1. Configurable parameters (change them with --name=value)
    // ------------------------------------------------------------------
    uint32_t nNodes = 10;       // number of mobile nodes
    double simTime = 60.0;      // total simulation time (s)
    uint32_t packetSize = 512;  // CBR payload size (bytes)
    double packetRate = 4.0;    // CBR packets per second
    double speed = 5.0;         // node speed (m/s)
    double pause = 0.0;         // pause time at each waypoint (s)
    double areaSize = 700.0;    // side of the square area (m)
    double range = 250.0;       // Wi-Fi transmission range (m)
    uint32_t seed = 1;          // random seed
    uint32_t run = 1;           // run number (different run = different random scenario)
    std::string protocol = "AODV";     // routing protocol: AODV, OLSR or DSDV
    std::string experiment = "single"; // label written into the CSV
    std::string csvFile = "results/csv/single_results.csv";
    std::string summaryFile = "results/summaries/single_summary.txt";

    CommandLine cmd(__FILE__);
    cmd.AddValue("nodes", "Number of mobile nodes (>= 2)", nNodes);
    cmd.AddValue("simTime", "Simulation time in seconds", simTime);
    cmd.AddValue("packetSize", "CBR packet (payload) size in bytes", packetSize);
    cmd.AddValue("packetRate", "CBR packets per second", packetRate);
    cmd.AddValue("speed", "Node speed in m/s", speed);
    cmd.AddValue("pause", "Pause time at each waypoint in s", pause);
    cmd.AddValue("area", "Side length of the square simulation area in m", areaSize);
    cmd.AddValue("range", "Wi-Fi transmission range in m", range);
    cmd.AddValue("seed", "Random seed", seed);
    cmd.AddValue("run", "Random run number", run);
    cmd.AddValue("protocol", "Routing protocol: AODV, OLSR or DSDV", protocol);
    cmd.AddValue("experiment", "Experiment label stored in the CSV", experiment);
    cmd.AddValue("csv", "CSV file to append results to", csvFile);
    cmd.AddValue("summary", "Human-readable summary file (empty = none)", summaryFile);
    cmd.Parse(argc, argv);

    if (protocol == "AODV")
    {
        g_routingPort = 654;
    }
    else if (protocol == "OLSR")
    {
        g_routingPort = 698;
    }
    else if (protocol == "DSDV")
    {
        g_routingPort = 269;
    }
    else
    {
        std::cerr << "Invalid --protocol=" << protocol << " (use AODV, OLSR or DSDV)" << std::endl;
        return 1;
    }

    if (nNodes < 2 || simTime <= 5.0 || packetRate <= 0.0 || speed <= 0.0 || packetSize < 12)
    {
        std::cerr << "Invalid parameters: need nodes>=2, simTime>5, packetRate>0, speed>0, "
                     "packetSize>=12"
                  << std::endl;
        return 1;
    }

    RngSeedManager::SetSeed(seed);
    RngSeedManager::SetRun(run);

    // Traffic starts after 2 s and stops 1 s before the end so that the last
    // packets have time to arrive (otherwise they would be counted as lost).
    const double trafficStart = 2.0;
    const double trafficStop = simTime - 1.0;
    const double trafficDuration = trafficStop - trafficStart;

    // ------------------------------------------------------------------
    // 2. Create nodes
    // ------------------------------------------------------------------
    NodeContainer nodes;
    nodes.Create(nNodes);

    // ------------------------------------------------------------------
    // 3. Wi-Fi: 802.11b, ad-hoc MAC, fixed 11 Mbps data rate
    // ------------------------------------------------------------------
    const std::string phyMode = "DsssRate11Mbps";
    // Send broadcast packets (route requests, hellos, updates) at the same rate as unicast.
    Config::SetDefault("ns3::WifiRemoteStationManager::NonUnicastMode", StringValue(phyMode));

    WifiHelper wifi;
    wifi.SetStandard(WIFI_STANDARD_80211b);
    wifi.SetRemoteStationManager("ns3::ConstantRateWifiManager",
                                 "DataMode",
                                 StringValue(phyMode),
                                 "ControlMode",
                                 StringValue(phyMode));

    YansWifiChannelHelper channel;
    channel.SetPropagationDelay("ns3::ConstantSpeedPropagationDelayModel");
    // Signal strength falls with distance (Friis free-space model) and nothing is
    // received beyond 'range' metres (the classic 250 m MANET radio range).
    channel.AddPropagationLoss("ns3::FriisPropagationLossModel");
    channel.AddPropagationLoss("ns3::RangePropagationLossModel", "MaxRange", DoubleValue(range));

    YansWifiPhyHelper phy;
    phy.SetChannel(channel.Create()); // default transmit power: 16 dBm

    WifiMacHelper mac;
    mac.SetType("ns3::AdhocWifiMac");

    NetDeviceContainer devices = wifi.Install(phy, mac, nodes);

    // ------------------------------------------------------------------
    // 4. Mobility: Random Waypoint inside an areaSize x areaSize square
    // ------------------------------------------------------------------
    std::ostringstream uniform;
    uniform << "ns3::UniformRandomVariable[Min=0.0|Max=" << areaSize << "]";

    ObjectFactory posFactory;
    posFactory.SetTypeId("ns3::RandomRectanglePositionAllocator");
    posFactory.Set("X", StringValue(uniform.str()));
    posFactory.Set("Y", StringValue(uniform.str()));
    Ptr<PositionAllocator> positionAlloc = posFactory.Create()->GetObject<PositionAllocator>();

    std::ostringstream speedStr;
    speedStr << "ns3::ConstantRandomVariable[Constant=" << speed << "]";
    std::ostringstream pauseStr;
    pauseStr << "ns3::ConstantRandomVariable[Constant=" << pause << "]";

    MobilityHelper mobility;
    mobility.SetPositionAllocator(positionAlloc); // initial positions
    mobility.SetMobilityModel("ns3::RandomWaypointMobilityModel",
                              "Speed",
                              StringValue(speedStr.str()),
                              "Pause",
                              StringValue(pauseStr.str()),
                              "PositionAllocator",
                              PointerValue(positionAlloc)); // next waypoints
    mobility.Install(nodes);

    // ------------------------------------------------------------------
    // 5. Internet stack with the chosen routing protocol + IPv4 addresses
    // ------------------------------------------------------------------
    AodvHelper aodv;
    OlsrHelper olsr;
    DsdvHelper dsdv;
    InternetStackHelper internet;
    if (protocol == "AODV")
    {
        internet.SetRoutingHelper(aodv);
    }
    else if (protocol == "OLSR")
    {
        internet.SetRoutingHelper(olsr);
    }
    else
    {
        internet.SetRoutingHelper(dsdv);
    }
    internet.Install(nodes);

    Ipv4AddressHelper address;
    address.SetBase("10.1.1.0", "255.255.255.0");
    Ipv4InterfaceContainer interfaces = address.Assign(devices);

    // Use fixed random streams so a given (seed, run) always gives the same result.
    int64_t stream = 1;
    stream += positionAlloc->AssignStreams(stream);
    stream += mobility.AssignStreams(nodes, stream);
    stream += wifi.AssignStreams(devices, stream);
    if (protocol == "AODV")
    {
        stream += aodv.AssignStreams(nodes, stream);
    }
    else if (protocol == "OLSR")
    {
        stream += olsr.AssignStreams(nodes, stream);
    }
    else
    {
        // DsdvHelper has no AssignStreams(), so set the stream on each node's protocol.
        for (uint32_t i = 0; i < nodes.GetN(); ++i)
        {
            Ptr<dsdv::RoutingProtocol> proto = DynamicCast<dsdv::RoutingProtocol>(
                nodes.Get(i)->GetObject<Ipv4>()->GetRoutingProtocol());
            stream += proto->AssignStreams(stream);
        }
    }

    // Count routing control packets sent by every node.
    Config::ConnectWithoutContext("/NodeList/*/$ns3::Ipv4L3Protocol/Tx",
                                  MakeCallback(&CountRoutingTx));

    // ------------------------------------------------------------------
    // 6. CBR UDP traffic: node 0 (source) -> node N-1 (destination)
    // ------------------------------------------------------------------
    const uint32_t srcIndex = 0;
    const uint32_t dstIndex = nNodes - 1;
    const uint16_t port = 9;
    const Ipv4Address srcAddr = interfaces.GetAddress(srcIndex);
    const Ipv4Address dstAddr = interfaces.GetAddress(dstIndex);

    UdpServerHelper server(port);
    ApplicationContainer serverApp = server.Install(nodes.Get(dstIndex));
    serverApp.Start(Seconds(1.0));
    serverApp.Stop(Seconds(simTime));

    UdpClientHelper client(InetSocketAddress(dstAddr, port));
    client.SetAttribute("MaxPackets", UintegerValue(0)); // 0 = unlimited
    client.SetAttribute("Interval", TimeValue(Seconds(1.0 / packetRate)));
    client.SetAttribute("PacketSize", UintegerValue(packetSize));
    ApplicationContainer clientApp = client.Install(nodes.Get(srcIndex));
    clientApp.Get(0)->TraceConnectWithoutContext("Tx", MakeCallback(&CountAppTx));
    clientApp.Start(Seconds(trafficStart));
    clientApp.Stop(Seconds(trafficStop));

    // ------------------------------------------------------------------
    // 7. FlowMonitor + run the simulation
    // ------------------------------------------------------------------
    FlowMonitorHelper flowHelper;
    Ptr<FlowMonitor> monitor = flowHelper.InstallAll();

    Simulator::Stop(Seconds(simTime));
    Simulator::Run();

    // ------------------------------------------------------------------
    // 8. Compute metrics for the CBR flow (src -> dst, UDP port 9)
    // ------------------------------------------------------------------
    monitor->CheckForLostPackets();
    Ptr<Ipv4FlowClassifier> classifier =
        DynamicCast<Ipv4FlowClassifier>(flowHelper.GetClassifier());

    uint64_t txPackets = 0;
    uint64_t rxPackets = 0;
    uint64_t rxBytes = 0;
    double delaySum = 0.0;  // seconds
    double jitterSum = 0.0; // seconds

    for (const auto& [flowId, stats] : monitor->GetFlowStats())
    {
        Ipv4FlowClassifier::FiveTuple t = classifier->FindFlow(flowId);
        // Keep only our data flow; ignore routing control traffic.
        if (t.sourceAddress == srcAddr && t.destinationAddress == dstAddr &&
            t.protocol == 17 && t.destinationPort == port)
        {
            txPackets += stats.txPackets;
            rxPackets += stats.rxPackets;
            rxBytes += stats.rxBytes;
            delaySum += stats.delaySum.GetSeconds();
            jitterSum += stats.jitterSum.GetSeconds();
        }
    }

    // Use the packets generated by the application as Tx (see the header comment).
    const uint64_t sourceDrops = (g_appTxPackets > txPackets) ? g_appTxPackets - txPackets : 0;
    txPackets = g_appTxPackets;
    const uint64_t lostPackets = (txPackets > rxPackets) ? txPackets - rxPackets : 0;
    const double pdr = txPackets ? 100.0 * rxPackets / txPackets : 0.0;
    const double lossRatio = txPackets ? 100.0 * lostPackets / txPackets : 0.0;
    const double throughputKbps = rxBytes * 8.0 / trafficDuration / 1000.0;
    const double avgDelayMs = rxPackets ? 1000.0 * delaySum / rxPackets : 0.0;
    const double avgJitterMs = rxPackets > 1 ? 1000.0 * jitterSum / (rxPackets - 1) : 0.0;
    const double nrl = rxPackets ? static_cast<double>(g_ctrlPackets) / rxPackets : 0.0;

    Simulator::Destroy();

    // ------------------------------------------------------------------
    // 9. Output: console, CSV (one row per run), text summary
    // ------------------------------------------------------------------
    std::ostringstream summary;
    summary << std::fixed << std::setprecision(3);
    summary << "==============================================================\n"
            << " " << protocol << " MANET Simulation Results (ns-3.48)\n"
            << "==============================================================\n"
            << " Parameters\n"
            << "   Routing protocol    : " << protocol << "\n"
            << "   Nodes               : " << nNodes << "\n"
            << "   Simulation time     : " << simTime << " s (traffic " << trafficStart
            << " s - " << trafficStop << " s)\n"
            << "   Area                : " << areaSize << " m x " << areaSize << " m\n"
            << "   Radio range         : " << range << " m\n"
            << "   Node speed / pause  : " << speed << " m/s / " << pause << " s\n"
            << "   Packet size         : " << packetSize << " bytes\n"
            << "   Packet rate         : " << packetRate << " packets/s\n"
            << "   Source -> Dest      : node " << srcIndex << " (" << srcAddr << ") -> node "
            << dstIndex << " (" << dstAddr << ")\n"
            << "   Seed / run          : " << seed << " / " << run << "\n"
            << " Metrics\n"
            << "   Transmitted packets : " << txPackets << "\n"
            << "   Received packets    : " << rxPackets << "\n"
            << "   Lost packets        : " << lostPackets << " (" << lossRatio << " %)\n"
            << "   Dropped at source   : " << sourceDrops << " (no route)\n"
            << "   Packet Delivery Ratio : " << pdr << " %\n"
            << "   Throughput          : " << throughputKbps << " kbps\n"
            << "   Average E2E delay   : " << avgDelayMs << " ms\n"
            << "   Average jitter      : " << avgJitterMs << " ms\n"
            << " Routing overhead\n"
            << "   Control packets     : " << g_ctrlPackets << " (" << g_ctrlBytes << " bytes)\n"
            << "   Normalised load     : " << nrl << " control packets per delivered packet\n"
            << "==============================================================\n";
    std::cout << summary.str();

    if (!csvFile.empty())
    {
        bool writeHeader;
        {
            std::ifstream check(csvFile);
            writeHeader = !check.good() || check.peek() == std::ifstream::traits_type::eof();
        }
        std::ofstream csv(csvFile, std::ios::app);
        if (!csv)
        {
            std::cerr << "ERROR: cannot open CSV file " << csvFile
                      << " (does the directory exist?)" << std::endl;
            return 1;
        }
        if (writeHeader)
        {
            csv << "experiment,protocol,nodes,sim_time_s,packet_size_B,packet_rate_pps,speed_mps,"
                   "pause_s,area_m,seed,run,tx_packets,rx_packets,lost_packets,loss_ratio_pct,"
                   "pdr_pct,throughput_kbps,avg_delay_ms,avg_jitter_ms,ctrl_packets,ctrl_bytes,"
                   "nrl,source_drops\n";
        }
        csv << std::fixed << std::setprecision(4) << experiment << "," << protocol << "," << nNodes << ","
            << simTime << "," << packetSize << "," << packetRate << "," << speed << "," << pause
            << "," << areaSize << "," << seed << "," << run << "," << txPackets << ","
            << rxPackets << "," << lostPackets << "," << lossRatio << "," << pdr << ","
            << throughputKbps << "," << avgDelayMs << "," << avgJitterMs << "," << g_ctrlPackets
            << "," << g_ctrlBytes << "," << nrl << "," << sourceDrops << "\n";
    }

    if (!summaryFile.empty())
    {
        std::ofstream out(summaryFile);
        if (!out)
        {
            std::cerr << "ERROR: cannot write summary file " << summaryFile << std::endl;
            return 1;
        }
        out << summary.str();
    }

    return 0;
}
